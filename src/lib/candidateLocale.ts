export function translateCandidateText(
  text: string,
  locale: CandidateLocale,
  values: CandidateTranslationValues = {}
): string {
  let translated = locale === 'bn' ? CANDIDATE_BENGALI[text] : undefined;
  let resolvedValues: CandidateTranslationValues = values;

  if (!translated && locale === 'bn') {
    for (const [template, candidate] of Object.entries(CANDIDATE_BENGALI)) {
      const parts = [...template.matchAll(/\{([a-zA-Z0-9_]+)\}/g)];
      if (!parts.length) continue;
      let pattern = '^';
      let cursor = 0;
      for (const part of parts) {
        const index = part.index ?? 0;
        pattern += template.slice(cursor, index).replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(.+?)';
        cursor = index + part[0].length;
      }
      pattern += template.slice(cursor).replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '$';
      const match = text.match(new RegExp(pattern));
      if (!match) continue;
      const captures = { ...values };
      parts.forEach((part, index) => {
        const key = part[1];
        if (captures[key] === undefined) captures[key] = match[index + 1];
      });
      translated = candidate;
      resolvedValues = captures;
      break;
    }
  }

  translated ||= text;
  return translated.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, key: string) => {
    const value = resolvedValues[key];
    return value === undefined ? placeholder : String(value);
  });
}
